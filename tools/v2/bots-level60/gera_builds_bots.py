# Regenerates mod-playerbots CoaLevelBuildData.h from the current talent trees. Max level = 5th argument (use 60; default 80 kept from 0.2.1).
# Keeps each specialization's original pick priority (ascensionsidekick builds) and re-times every pick to the first
# level where the new CharacterAdvancement.dbc allows it: required level (field 26), tab gate (dwords 38/39, points
# already spent in the tab on lower-gate rows), required entries (fields 2-4) and the essence budget of that level.
# Points left over above the original top level go to the other paid rows of the same trees, bottom row first.
import re, struct, sys, collections

SRC_H, DBC, ESS, OUT = sys.argv[1:5]
MAXL = int(sys.argv[5]) if len(sys.argv) > 5 else 80

def load(p):
    b = open(p, "rb").read()
    m, c, f, rs, ss = struct.unpack("<4sIIII", b[:20])
    return [b[20 + i * rs:20 + (i + 1) * rs] for i in range(c)]

u = lambda r, i: struct.unpack_from("<I", r, i * 4)[0]
ub = lambda r, o: struct.unpack_from("<I", r, o)[0]
fl = lambda r, o: struct.unpack_from("<f", r, o)[0]

rows = {}
for r in load(DBC):
    if ub(r, 479) & 0x9:
        continue
    spells = [u(r, i) for i in range(5, 10) if u(r, i)]
    rows[u(r, 0)] = dict(id=u(r, 0), ct=u(r, 32), tab=u(r, 33), ae=u(r, 14), te=u(r, 15), lvl=u(r, 26),
                         gate=u(r, 39) if u(r, 15) else u(r, 38), req=[u(r, i) for i in (2, 3, 4) if u(r, i)],
                         ranks=max(1, len(spells)), y=fl(r, 402), x=fl(r, 398), group=u(r, 29))

budget = collections.defaultdict(dict)
for r in load(ESS):
    v = struct.unpack_from("<9I", r)
    if v[3] == 0 and v[4] == 0 and v[5] == 0 and v[6] == 0:
        budget[v[2]][v[1]] = (v[7], v[8])

text = open(SRC_H).read()
picks = [tuple(map(int, m)) for m in re.findall(r"\{(\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\}", text)]
print("picks originais:", len(picks))

byspec = collections.OrderedDict()
for p in picks:
    byspec.setdefault((p[0], p[1]), []).append(p)

out = []
report = []
for (cls, spec), plist in byspec.items():
    plist = sorted(plist, key=lambda p: p[2])  # stable: keeps list order inside a level
    queue = []           # (entry, rank, tree) increments in priority order
    for p in plist:
        e = rows.get(p[4])
        if not e or not (e["ae"] or e["te"]):
            continue
        queue.append((p[4], min(p[5], e["ranks"]), p[3]))
    tabs = {0: set(), 1: set()}
    for ent, _, tree in queue:
        tabs[tree].add(rows[ent]["tab"])
    have = {}
    spent = [0, 0]

    def invested(tab, gate, tree):
        return sum(rows[k]["ae" if tree == 0 else "te"] * v for k, v in have.items()
                   if rows[k]["tab"] == tab and rows[k]["gate"] < gate)

    def can(ent, rank, tree, L):
        e = rows[ent]
        if have.get(ent, 0) >= rank or e["lvl"] > L:
            return False
        if e["gate"] and invested(e["tab"], e["gate"], tree) < e["gate"]:
            return False
        if any(q in rows and (rows[q]["ae"] or rows[q]["te"]) and not have.get(q) for q in e["req"]):
            return False
        cost = (e["ae"] if tree == 0 else e["te"]) * (rank - have.get(ent, 0))
        return spent[tree] + cost <= budget[cls].get(L, (0, 0))[tree]

    def take(ent, rank, tree, L):
        e = rows[ent]
        spent[tree] += (e["ae"] if tree == 0 else e["te"]) * (rank - have.get(ent, 0))
        have[ent] = rank
        out.append((cls, spec, L, tree, ent, rank))

    filler = {t: sorted([e for e in rows.values() if e["tab"] in tabs[t] and e["ct"] == rows[queue[0][0]]["ct"]
                         and (e["ae"] if t == 0 else e["te"]) and not e["group"]],
                        key=lambda e: (e["y"], e["x"], e["id"])) for t in (0, 1)} if queue else {0: [], 1: []}
    for L in range(10, MAXL + 1):
        progressed = True
        while progressed:
            progressed = False
            for i, (ent, rank, tree) in enumerate(queue):
                if can(ent, rank, tree, L):
                    take(ent, rank, tree, L)
                    queue.pop(i)
                    progressed = True
                    break
            if progressed or L < MAXL:
                continue
            for tree in (0, 1):
                for e in filler[tree]:
                    r = have.get(e["id"], 0) + 1
                    if r <= e["ranks"] and can(e["id"], r, tree, L):
                        take(e["id"], r, tree, L)
                        progressed = True
                        break
                if progressed:
                    break
    b80 = budget[cls].get(MAXL, (0, 0))
    report.append((cls, spec, spent[0], spent[1], b80[0], b80[1], len(queue)))

out.sort(key=lambda p: (p[0], p[1], p[2], p[3]))
body = ",\n".join("    {%d, %d, %d, %d, %d, %d}" % p for p in out)
header = text[:text.index("inline constexpr std::array<Pick,")]
header = header.replace("// Generated by Generer-Builds-Bots.py",
    "// ShadowCore 0.2.5 (18/10/2026): re-timed to the level-60 trees by gera_builds_bots.py (MAXL 60), from\n// the original Generer-Builds-Bots.py table")
open(OUT, "w").write(header + "inline constexpr std::array<Pick, %d> Picks =\n{{\n%s,\n}};\n}\n\n#endif\n" % (len(out), body))
print("picks novos:", len(out))
under = [r for r in report if r[2] < r[4] - 1 or r[3] < r[5] - 1]
print("specs:", len(report), "| gastam no 80 (hab/tal): min %d/%d" % (min(r[2] for r in report), min(r[3] for r in report)),
      "| abaixo do orcamento-1:", len(under), under[:8])
print("picks da build original nunca possiveis:", sum(r[6] for r in report))
